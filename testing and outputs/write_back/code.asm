#--------------------------------
# I2C MASTER -> SLAVE
#--------------------------------
lui   x5,0x40000
addi  x5,x5,20

lui   x6,0x402C0
sw    x6,0(x5)


#--------------------------------
# UART -> DEADBEEF
#--------------------------------
lui   x5,0x40000

lui   x6,0xDEADC
addi  x6,x6,-273
sw    x6,0(x5)


#--------------------------------
# PWM -> 1 MHz, 20% duty
#--------------------------------
addi  x5,x5,8

lui   x6,0x00640
addi  x6,x6,20
sw    x6,0(x5)


#--------------------------------
# TIMER 1
#--------------------------------
addi  x5,x5,4

lui   x6,0x0C0A0
addi  x6,x6,6
sw    x6,0(x5)


#--------------------------------
# TIMER 2
#--------------------------------
lui   x6,0x0E000
addi  x6,x6,10
sw    x6,0(x5)


#--------------------------------
# I2C SLAVE -> MASTER
#--------------------------------
lui   x5,0x40000
addi  x5,x5,20

lui   x6,0x413C0
sw    x6,0(x5)


#--------------------------------
# POLL I2C READY
#--------------------------------
poll:
lw    x5,31(x0)
beq   x5,x0,poll

#--------------------------------
# READ I2C DATA
#--------------------------------
lw    x12,8(x0)

beq   x0,x0,0
